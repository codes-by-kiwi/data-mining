from collections import defaultdict
import numpy as np
from scipy.sparse import csr_matrix

class MinHashLSH:
    def __init__(self, data_path, num_permutations, num_bands, rows_per_band, num_buckets=2**16):
        self.data_path = data_path
        self.num_permutations = num_permutations
        self.num_bands = num_bands
        self.rows_per_band = rows_per_band
        self.num_buckets = num_buckets
        self.sparse_matrix = None
        self.signatures = None
        self.candidate_buckets_sorted = None

    def load_data(self):
        """Load the user-movie data and create a sparse matrix."""
        data = np.load(self.data_path)
        users = data[:, 0]
        movies = data[:, 1]
        self.sparse_matrix = csr_matrix((np.ones_like(users), (movies - 1, users - 1))) # Create the sparse matrix

    def generate_minhash_signatures(self, random_seed):
        """Generate MinHash signatures."""
        if random_seed is not None:
            np.random.seed(random_seed)

        num_movies, num_users = self.sparse_matrix.shape
        signatures = np.full((self.num_permutations, num_users), np.inf) # Initialize the signature matrix with infinity
        hash_functions = [np.random.permutation(num_movies) for _ in range(self.num_permutations)] # Generate permutations of the movies
        inverse_hash_functions = [np.argsort(h) for h in hash_functions] # To represent the position of each movie in the permuation

        for row_idx in range(num_movies):
            row = self.sparse_matrix[row_idx, :] # Access the sparse row
            if row.nnz == 0: # Skip empty rows (if any)
                continue

            user_indices = row.indices  # Get the users (columns) that rated this movie
            for perm_idx in range(self.num_permutations): # For each hash function (permutation)
                hash_value = inverse_hash_functions[perm_idx][row_idx]  # Retrieve the position of row_idx in the permutation
                signatures[perm_idx, user_indices] = np.minimum(signatures[perm_idx, user_indices], hash_value) # Update the signatures using the minimum value

        self.signatures = signatures

    def perform_lsh(self):
        """Perform Locality Sensitive Hashing (LSH)."""
        num_hashes, num_users = self.signatures.shape
        candidate_buckets = []
        # Process each band
        for band_idx in range(self.num_bands):
            start_row = band_idx * self.rows_per_band # Extract rows corresponding to the current band
            end_row = min(start_row + self.rows_per_band, num_hashes) # Handle shorter signatures
            band = self.signatures[start_row:end_row, :]

            # Hash columns (users) in the band into buckets
            buckets = defaultdict(list)
            for user_idx in range(num_users):
                band_hash = hash(tuple(band[:, user_idx])) % self.num_buckets
                buckets[band_hash].append(user_idx)

            # Store each bucket with its size
            for bucket_users in buckets.values():
                candidate_buckets.append((len(bucket_users), bucket_users))

        self.candidate_buckets_sorted = sorted(candidate_buckets, key=lambda x: x[0])

    def compute_jaccard_similarity(self, threshold=0.5, max_pairs=200, output_file="similar_pairs_found.txt"):
        """Compute Jaccard Similarities for sorted candidate buckets and write to file."""
        sparse_matrix_csc = self.sparse_matrix.tocsc()
        found_pairs = 0
        checked_pairs = defaultdict(set)

        with open(output_file, "w") as file:
            for _, bucket_users in self.candidate_buckets_sorted:
                # Generate all unique pairs from the bucket
                for i in range(len(bucket_users)):
                    for j in range(i + 1, len(bucket_users)):
                        u1, u2 = bucket_users[i], bucket_users[j]

                        # Ensure pair (u1, u2) is ordered as (min, max) to avoid duplicates
                        if u1 > u2:
                            u1, u2 = u2, u1

                        # Skip if already checked (no need to test pairs that have been tested)
                        if u2 in checked_pairs[u1]:
                            continue
                        checked_pairs[u1].add(u2)

                        # Get the sets of movies rated by user u1 and user u2
                        movies_u1 = sparse_matrix_csc[:, u1]
                        movies_u2 = sparse_matrix_csc[:, u2]

                        # Compute intersection and the union sizes
                        intersection_size = movies_u1.multiply(movies_u2).nnz
                        union_size = (movies_u1 + movies_u2).nnz

                        if union_size > 0:
                            jaccard_similarity = intersection_size / union_size
                            if jaccard_similarity >= threshold:
                                file.write(f"{u1 + 1},{u2 + 1}\n")
                                file.flush()  # Flush after writing to ensure it's immediately saved

                                found_pairs += 1
                        # Stop if the desired number of pairs is found to avoid exceeding the 30 minutes
                        if found_pairs >= max_pairs:
                            return

    def run(self):
        """Run the full MinHash and LSH pipeline."""

        while True:
            user_input = input("Enter a random seed (integer): ")
            try:
                random_seed = int(user_input)
                break
            except ValueError:
                print("Invalid input! Please enter an integer.")

        self.load_data()
        self.generate_minhash_signatures(random_seed)
        self.perform_lsh()
        self.compute_jaccard_similarity()

